let cart = [];
window._cart = cart;

function toggleCart(){
  const overlay = document.getElementById("cartOverlay");
  const drawer = document.getElementById("cartDrawer");
  overlay.classList.toggle("open");
  drawer.classList.toggle("open");
}

document.addEventListener("DOMContentLoaded", () => {
  const toggle = document.getElementById("cartToggle");
  if(toggle) toggle.addEventListener("click", toggleCart);
  const saved = sessionStorage.getItem("nrs_cart");
  if(saved){ const parsed = JSON.parse(saved); parsed.forEach(i => cart.push(i)); window._cart = cart; renderCart(); }
});

function addToCart(btn, name, price){
  const existing = cart.find(i => i.name === name);
  if(existing){ existing.qty++; } else { cart.push({ name, price, qty: 1 }); }
  window._cart = cart;
  if(btn){ btn.textContent = "✓ Aggiunto"; btn.classList.add("added"); setTimeout(() => { btn.textContent = "+ Aggiungi"; btn.classList.remove("added"); }, 1800); }
  renderCart();
}

function removeFromCart(index){ cart.splice(index, 1); window._cart = cart; renderCart(); }

function renderCart(){
  const items = document.getElementById("cartItems");
  const empty = document.getElementById("cartEmpty");
  const total = document.getElementById("cartTotal");
  const count = document.getElementById("cartCount");
  if(!items) return;
  const totalQty = cart.reduce((s, i) => s + i.qty, 0);
  const totalVal = cart.reduce((s, i) => s + i.price * i.qty, 0);
  if(count) count.textContent = totalQty;
  if(total) total.textContent = totalVal;
  const oldItems = items.querySelectorAll(".cart-item");
  oldItems.forEach(el => el.remove());
  if(cart.length === 0){ if(empty) empty.style.display = "block"; }
  else {
    if(empty) empty.style.display = "none";
    cart.forEach((item, idx) => {
      const el = document.createElement("div");
      el.className = "cart-item";
      el.innerHTML = `
        <div class="cart-item-img">
          <svg viewBox="0 0 56 56" fill="none" xmlns="http://www.w3.org/2000/svg" style="width:32px;height:32px">
            <rect width="56" height="56" fill="#111"/>
            <text x="28" y="34" text-anchor="middle" font-family="'Bebas Neue',sans-serif" font-size="14" fill="#ff2d00" letter-spacing="1">NRS</text>
          </svg>
        </div>
        <div class="cart-item-info">
          <div class="cart-item-name">${item.name}</div>
          <div class="cart-item-price">€${item.price} × ${item.qty}</div>
        </div>
        <button class="cart-item-remove" onclick="removeFromCart(${idx})">×</button>
      `;
      items.appendChild(el);
    });
  }
}

function goToCheckout(){
  sessionStorage.setItem("nrs_cart", JSON.stringify(window._cart || []));
  window.location.href = "./checkout.html";
}
